#!/usr/bin/env bash
# Stamp the vendored kernel's build identity with the UPSTREAM commit.
#
# Why this exists: the vendored tree lives inside Warren's git repository, so the
# daemon's build-identity stamp picks up *Warren's* HEAD and a `dirty: true` flag
# of our own making. `/healthz` then reports a commit that is not the kernel's —
# a quiet lie in the one field a support request is read against.
#
# upstream computes its stamp once at package time and overwrites the compiled
# `dist/build-info.js` (see packages/daemon/src/build-info.ts). This does the
# same for the vendored copy, using the sha recorded in vendor/openrig/UPSTREAM.md,
# which is the provenance source of truth for the absorbed tree.
#
#   scripts/openrig-vendor-stamp.sh            # stamp from UPSTREAM.md
#   scripts/openrig-vendor-stamp.sh --check    # fail if any stamp disagrees
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENDOR="$REPO_ROOT/vendor/openrig"
UPSTREAM_MD="$VENDOR/UPSTREAM.md"

check_only=0
[ "${1:-}" = "--check" ] && check_only=1

sha="$(sed -n 's/^| Snapshot sha | `\([0-9a-f]\{7,\}\)` |$/\1/p' "$UPSTREAM_MD" | head -n1)"
[ -n "$sha" ] || { printf 'openrig-vendor-stamp: no sha in %s\n' "$UPSTREAM_MD" >&2; exit 1; }

# The semver the stamped tree reports. Upstream's own default; override to test.
semver="${OPENRIG_VENDOR_SEMVER:-0.6.10}"

mapfile -t stamps < <(find "$VENDOR/packages" -path '*/dist/build-info.js' -not -path '*/node_modules/*' 2>/dev/null)
[ "${#stamps[@]}" -gt 0 ] || { printf 'openrig-vendor-stamp: no dist/build-info.js yet — build first (npm run build)\n' >&2; exit 1; }

fail=0
for file in "${stamps[@]}"; do
  rel="${file#"$REPO_ROOT"/}"
  if [ "$check_only" = 1 ]; then
    if grep -q "\"$sha\"" "$file" && grep -q 'dirty: false' "$file"; then
      printf 'ok   %s\n' "$rel"
    else
      printf 'FAIL %s does not carry %s\n' "$rel" "$sha" >&2
      fail=1
    fi
    continue
  fi
  built_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  cat > "$file" <<EOF
// GENERATED by warren's scripts/openrig-vendor-stamp.sh — the vendored build's
// identity. Do not edit: upstream regenerates this file at package time, and our
// stamp replaces the value their build reads out of Warren's own git HEAD.
export const BUILD_INFO = {
  semver: "$semver",
  commit: "$sha",
  dirty: false,
  builtAt: "$built_at",
};
export function stampFields(info = BUILD_INFO) {
  if (!info.commit) return {};
  return { semver: info.semver, commit: info.commit, dirty: info.dirty, builtAt: info.builtAt };
}
EOF
  printf 'stamped %s -> %s\n' "$rel" "$sha"
done

[ "$fail" = 0 ] || exit 1
